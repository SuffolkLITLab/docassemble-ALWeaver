import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';

const target = new URL(
  '../docassemble/ALWeaver/data/static/faker_en_us.js',
  import.meta.url,
);
const result = await build({
  entryPoints: [new URL('./faker_browser_entry.mjs', import.meta.url).pathname],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['es2021'],
  write: false,
  legalComments: 'inline',
  banner: {
    js: '// Generated by npm run build:faker. Do not edit.\n// @ts-nocheck',
  },
});
const content = result.outputFiles[0].text;
const licenseTarget = new URL(
  '../docassemble/ALWeaver/data/static/faker_LICENSE.txt',
  import.meta.url,
);
const license = await readFile(
  new URL('../node_modules/@faker-js/faker/LICENSE', import.meta.url),
  'utf8',
);
if (process.argv.includes('--check')) {
  if (
    (await readFile(target, 'utf8')) !== content ||
    (await readFile(licenseTarget, 'utf8')) !== license
  ) {
    throw new Error('Faker bundle is stale. Run npm run build:faker.');
  }
} else {
  await writeFile(target, content);
  await writeFile(licenseTarget, license);
}
